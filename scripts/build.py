#!/usr/bin/env python3
"""Regenerate .claude-plugin/marketplace.json and SKILLS.md from skills/.

Run from anywhere: python3 scripts/build.py
Never edit those two files by hand.
"""
import json
import sys

sys.path.insert(0, str(__import__("pathlib").Path(__file__).resolve().parent))
from skills_lib import ROOT, collect_skills  # noqa: E402

KEYWORDS = ["buddhism", "buddhist-texts"]


def build():
    skills, languages = collect_skills()
    neutral = [s for s in skills if s["language"] is None]
    by_lang = {}
    for s in skills:
        if s["language"]:
            by_lang.setdefault(s["language"], []).append(s)

    plugins = [{
        "name": "buddhist-skills",
        "source": "./",
        "strict": False,
        "description": "Every BuddhistAI skill, all languages.",
        "category": "productivity",
        "keywords": KEYWORDS,
        "skills": [s["path"] for s in skills],
    }]
    for lang in sorted(by_lang):
        title = lang.replace("-", " ").title()
        plugins.append({
            "name": f"buddhist-skills-{lang}",
            "source": "./",
            "strict": False,
            "description": f"BuddhistAI skills for {title} texts, plus the language-neutral ones.",
            "category": "productivity",
            "keywords": KEYWORDS + [lang, languages[lang]["code"]],
            "skills": [s["path"] for s in by_lang[lang] + neutral],
        })
    marketplace = {
        "name": "buddhistai",
        "owner": {"name": "BuddhistAI", "url": "https://github.com/BuddhistAI"},
        "description": "Open agent skills for Buddhist text work, one plugin per language. Each skill is the current benchmark winner for its task and language.",
        "plugins": plugins,
    }

    lines = [
        "# Skill catalog",
        "",
        "_Generated by `scripts/build.py`. Do not edit by hand._",
        "",
        "Install one language with `claude plugin install buddhist-skills-<language>@buddhistai`.",
        "",
    ]
    lines += ["## Language-neutral", ""]
    lines += [f"- **[{s['name']}](./skills/{s['name']}/SKILL.md)**: {s['top'].get('description', '')}" for s in neutral] or ["_None._"]
    lines.append("")
    for lang in sorted(by_lang):
        code = languages[lang]["code"]
        lines += [f"## {lang.replace('-', ' ').title()} (`{code}`)", "", "| Skill | Task | Benchmark | Score | Version |", "| --- | --- | --- | --- | --- |"]
        for s in by_lang[lang]:
            m = s["meta"]
            lines.append(f"| [{s['name']}](./skills/{s['name']}/SKILL.md) | {s['task']} | {m.get('benchmark', '')} | {m.get('score', '')} | {m.get('version', '')} |")
        lines.append("")
    if not by_lang:
        lines += ["## Language skills", "", "_None promoted yet._", ""]
    return json.dumps(marketplace, indent=2, ensure_ascii=False) + "\n", "\n".join(lines)


def main():
    marketplace, catalog = build()
    (ROOT / ".claude-plugin" / "marketplace.json").write_text(marketplace, encoding="utf-8")
    (ROOT / "SKILLS.md").write_text(catalog, encoding="utf-8")
    print("Wrote .claude-plugin/marketplace.json and SKILLS.md")


if __name__ == "__main__":
    main()
